// Draws the paw-print watermark tile once and writes it into
// src/lib/watermarkTile.ts. The preview repeats this tile over the portrait,
// on Cloudflare (Images binding) and in local dev alike, so both look the same.
//
//   npx tsx scripts/make-watermark-tile.ts

import { encode } from "fast-png";
import { writeFileSync } from "node:fs";

// Sparse and soft: enough that nobody prints the preview, light enough that a
// shared preview still looks like a portrait. Paws sit 210px apart, rows
// 168px apart, every other row shifted half a step; the tile holds two rows.
const STEP = 210;
const W = STEP;
const H = Math.round(STEP * 0.8 * 2);
const SCALE = 1.25;
const PAWS = [
  { x: STEP * 0.15, y: STEP * 0.4 },
  { x: STEP / 2, y: STEP * 0.4 + STEP * 0.8 },
];
// A paw print drawn with shapes, not text. Pad, then four toes, in paw units.
const SHAPES = [
  { cx: 0, cy: 14, rx: 15, ry: 12 },
  { cx: -16, cy: -6, rx: 6, ry: 8 },
  { cx: -6, cy: -16, rx: 6, ry: 8 },
  { cx: 6, cy: -16, rx: 6, ry: 8 },
  { cx: 16, cy: -6, rx: 6, ry: 8 },
];

const rgba = new Float64Array(W * H * 4);
// Porter-Duff "over" onto the transparent tile, in straight alpha.
function over(i: number, value: number, alpha: number) {
  const a0 = rgba[i + 3];
  const a = alpha + a0 * (1 - alpha);
  if (a === 0) return;
  for (let k = 0; k < 3; k++) rgba[i + k] = (value * alpha + rgba[i + k] * a0 * (1 - alpha)) / a;
  rgba[i + 3] = a;
}

const angle = (-20 * Math.PI) / 180;
const [cos, sin] = [Math.cos(angle), Math.sin(angle)];
for (let y = 0; y < H; y++) {
  for (let x = 0; x < W; x++) {
    // Distance to the nearest paw edge in pixels, counting paws that wrap
    // around the tile's edges so the repeat is seamless.
    let d = Infinity;
    for (const paw of PAWS) {
      for (const ox of [-W, 0, W]) {
        for (const oy of [-H, 0, H]) {
          const dx = (x + 0.5 - paw.x - ox) / SCALE;
          const dy = (y + 0.5 - paw.y - oy) / SCALE;
          if (Math.abs(dx) > 30 || Math.abs(dy) > 30) continue;
          const ux = dx * cos + dy * sin;
          const uy = -dx * sin + dy * cos;
          for (const e of SHAPES) d = Math.min(d, (Math.hypot((ux - e.cx) / e.rx, (uy - e.cy) / e.ry) - 1) * Math.min(e.rx, e.ry) * SCALE);
        }
      }
    }
    const i = (y * W + x) * 4;
    const fill = Math.min(1, Math.max(0, 0.5 - d));
    if (fill > 0) over(i, 255, 0.3 * fill);
    const edge = Math.min(1, Math.max(0, 1.25 - Math.abs(d)));
    if (edge > 0) over(i, 0, 0.1 * edge);
  }
}

const png = encode({ width: W, height: H, data: Uint8Array.from(rgba, (v, i) => Math.round(i % 4 === 3 ? v * 255 : v)), channels: 4, depth: 8 });
writeFileSync(
  "src/lib/watermarkTile.ts",
  `// Generated by scripts/make-watermark-tile.ts. Don't edit by hand.\n` +
    `// ${W}x${H} transparent PNG with two paw prints, repeated over every preview.\n` +
    `export const TILE_PNG_BASE64 =\n  "${Buffer.from(png).toString("base64")}";\n`,
);
console.log(`Wrote a ${W}x${H} tile, ${png.length} bytes.`);
